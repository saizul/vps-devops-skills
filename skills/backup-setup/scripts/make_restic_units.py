#!/usr/bin/env python3
"""Generate a restic backup setup: script, systemd service + timer, env template.

Nothing is installed or run. The files are written to --out (or printed with
--dry-run) so you can review them, then copy them into place yourself.

Generated files:
  restic-<name>.sh        backup + optional DB dumps + forget/prune + check
  restic-<name>.service   oneshot unit running the script
  restic-<name>.timer     schedule (OnCalendar, Persistent, RandomizedDelaySec)
  restic-<name>.env.example  repository + credential variable names (no values)
  restic-<name>.excludes  default exclude patterns

Exit codes: 0 = ok, 2 = invalid arguments or output exists.
"""

from __future__ import annotations

import argparse
import re
import shlex
import sys
from pathlib import Path

REPO_PREFIXES = {
    "s3:": ["AWS_ACCESS_KEY_ID", "AWS_SECRET_ACCESS_KEY"],
    "b2:": ["B2_ACCOUNT_ID", "B2_ACCOUNT_KEY"],
    "sftp:": [],
    "rclone:": [],
    "rest:": [],
    "azure:": ["AZURE_ACCOUNT_NAME", "AZURE_ACCOUNT_KEY"],
    "gs:": ["GOOGLE_PROJECT_ID", "GOOGLE_APPLICATION_CREDENTIALS"],
    "swift:": ["OS_AUTH_URL", "OS_USERNAME", "OS_PASSWORD"],
    "/": [],
}

DEFAULT_EXCLUDES = [
    "/var/lib/docker/overlay2",
    "/var/cache",
    "/var/tmp",
    "/tmp",
    "**/node_modules",
    "**/.cache",
    "**/__pycache__",
    "*.swp",
]

NAME_RE = re.compile(r"^[a-z0-9][a-z0-9-]{0,40}$")
ONCALENDAR_RE = re.compile(r"^[A-Za-z0-9*,./:\- ~]+$")


def repo_env_vars(repo: str) -> list[str]:
    for prefix, env in REPO_PREFIXES.items():
        if repo.startswith(prefix):
            return env
    raise ValueError(
        f"unsupported repository '{repo}'. Use one of: " + ", ".join(p + "..." for p in REPO_PREFIXES)
    )


def build_script(args) -> str:
    q = shlex.quote
    lines = [
        "#!/bin/sh",
        f"# restic backup '{args.name}'. Generated by make_restic_units.py; review before use.",
        "set -eu",
        "",
        "# Credentials and RESTIC_REPOSITORY come from the EnvironmentFile in the service unit.",
        ': "${RESTIC_REPOSITORY:?set RESTIC_REPOSITORY}"',
        ': "${RESTIC_PASSWORD_FILE:?set RESTIC_PASSWORD_FILE}"',
        "",
        f"TAG={q(args.name)}",
        f"EXCLUDES={q(str(Path(args.config_dir) / f'restic-{args.name}.excludes'))}",
    ]
    if args.mysql or args.postgres:
        lines += [
            f"DUMP_DIR={q(args.dump_dir)}",
            'umask 077; mkdir -p "$DUMP_DIR"',
        ]
    if args.mysql:
        lines += [
            "",
            "# MySQL/MariaDB: consistent dump without locking InnoDB tables.",
            "# Auth via /root/.my.cnf or the unix socket (root), never a password on the CLI.",
            "mysqldump --all-databases --single-transaction --quick --routines --events \\",
            '  | gzip > "$DUMP_DIR/mysql-all.sql.gz.tmp"',
            'mv "$DUMP_DIR/mysql-all.sql.gz.tmp" "$DUMP_DIR/mysql-all.sql.gz"',
        ]
    if args.postgres:
        lines += [
            "",
            "# PostgreSQL: dump every database as the postgres OS user.",
            'runuser -u postgres -- pg_dumpall | gzip > "$DUMP_DIR/postgres-all.sql.gz.tmp"',
            'mv "$DUMP_DIR/postgres-all.sql.gz.tmp" "$DUMP_DIR/postgres-all.sql.gz"',
        ]
    paths = list(args.path)
    if (args.mysql or args.postgres) and args.dump_dir not in paths:
        paths.append(args.dump_dir)
    lines += [
        "",
        "restic snapshots --latest 1 >/dev/null 2>&1 || {",
        '  echo "repository not reachable or not initialised: run restic init first" >&2',
        "  exit 1",
        "}",
        "",
        'restic backup --tag "$TAG" --exclude-file "$EXCLUDES" --exclude-caches \\',
        "  --one-file-system \\",
        "  " + " ".join(q(p) for p in paths),
        "",
        'restic forget --tag "$TAG" --group-by host,tags --prune \\',
        f"  --keep-daily {args.keep_daily} --keep-weekly {args.keep_weekly} "
        f"--keep-monthly {args.keep_monthly}",
        "",
        "# Verify repository structure and read a random sample of the data.",
        f"restic check --read-data-subset={q(args.check_subset)}",
        "",
    ]
    return "\n".join(lines)


def build_service(args) -> str:
    cfg = Path(args.config_dir)
    unit = [
        "[Unit]",
        f"Description=restic backup ({args.name})",
        "Wants=network-online.target",
        "After=network-online.target",
    ]
    if args.on_failure:
        unit.append(f"OnFailure={args.on_failure}")
    unit += [
        "",
        "[Service]",
        "Type=oneshot",
        f"EnvironmentFile={cfg / f'restic-{args.name}.env'}",
        "Environment=RESTIC_CACHE_DIR=/var/cache/restic",
        f"ExecStart=/bin/sh {cfg / f'restic-{args.name}.sh'}",
        "Nice=10",
        "IOSchedulingClass=idle",
        "PrivateTmp=true",
        "ProtectSystem=full",
        "NoNewPrivileges=true",
        f"TimeoutStartSec={args.timeout}",
        "",
    ]
    return "\n".join(unit)


def build_timer(args) -> str:
    return "\n".join(
        [
            "[Unit]",
            f"Description=Schedule restic backup ({args.name})",
            "",
            "[Timer]",
            f"OnCalendar={args.schedule}",
            "Persistent=true",
            f"RandomizedDelaySec={args.random_delay}",
            "",
            "[Install]",
            "WantedBy=timers.target",
            "",
        ]
    )


def build_env(args) -> str:
    lines = [
        f"# /etc/restic/restic-{args.name}.env  (chmod 600, owned by root). Never commit this file.",
        f"RESTIC_REPOSITORY={args.repo}",
        f"RESTIC_PASSWORD_FILE={Path(args.config_dir) / f'restic-{args.name}.password'}",
    ]
    for var in repo_env_vars(args.repo):
        lines.append(f"{var}=")
    if args.repo.startswith("rclone:"):
        lines.append("# rclone remotes are read from root's rclone config (rclone config file)")
    lines.append("")
    return "\n".join(lines)


def build_files(args) -> dict[str, str]:
    n = args.name
    return {
        f"restic-{n}.sh": build_script(args),
        f"restic-{n}.service": build_service(args),
        f"restic-{n}.timer": build_timer(args),
        f"restic-{n}.env.example": build_env(args),
        f"restic-{n}.excludes": "\n".join(DEFAULT_EXCLUDES + list(args.exclude)) + "\n",
    }


def install_steps(args) -> str:
    n, cfg = args.name, args.config_dir
    return f"""Next steps (run them yourself after reviewing the files):
  sudo apt install restic
  sudo install -d -m 700 {cfg}
  sudo install -m 700 restic-{n}.sh {cfg}/
  sudo install -m 600 restic-{n}.excludes {cfg}/
  sudo install -m 600 restic-{n}.env.example {cfg}/restic-{n}.env   # then fill in credentials
  sudo sh -c 'umask 077; openssl rand -base64 32 > {cfg}/restic-{n}.password'
  # Store a copy of the password OFF this server (password manager). Lost password = lost backups.
  sudo sh -c 'set -a; . {cfg}/restic-{n}.env; restic init'
  sudo install -m 644 restic-{n}.service restic-{n}.timer /etc/systemd/system/
  sudo systemctl daemon-reload
  sudo systemctl start restic-{n}.service && journalctl -u restic-{n}.service -n 50
  sudo systemctl enable --now restic-{n}.timer && systemctl list-timers 'restic-*'
Then do a restore drill (see references/restore-drill.md)."""


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(
        description="Generate restic backup script + systemd units (writes files only).",
    )
    p.add_argument("--name", default="system", help="job name, e.g. 'system' or 'app' (default: system)")
    p.add_argument(
        "--repo",
        required=True,
        help="restic repository, e.g. s3:s3.amazonaws.com/bucket/host, "
        "sftp:user@host:/srv/restic, rclone:remote:path, b2:bucket:path",
    )
    p.add_argument(
        "--path",
        action="append",
        default=[],
        help="path to back up (repeatable; default: /etc /home /root /var/www /srv)",
    )
    p.add_argument("--exclude", action="append", default=[], help="extra exclude pattern (repeatable)")
    p.add_argument("--mysql", action="store_true", help="dump all MySQL/MariaDB databases before the backup")
    p.add_argument("--postgres", action="store_true", help="dump all PostgreSQL databases before the backup")
    p.add_argument(
        "--dump-dir", default="/var/backups/db", help="where DB dumps are written (default: /var/backups/db)"
    )
    p.add_argument(
        "--schedule", default="*-*-* 03:15:00", help="systemd OnCalendar expression (default: daily 03:15)"
    )
    p.add_argument("--random-delay", default="15min", help="RandomizedDelaySec (default: 15min)")
    p.add_argument("--keep-daily", type=int, default=7)
    p.add_argument("--keep-weekly", type=int, default=4)
    p.add_argument("--keep-monthly", type=int, default=6)
    p.add_argument(
        "--check-subset", default="5%", help="restic check --read-data-subset value (default: 5%%)"
    )
    p.add_argument("--config-dir", default="/etc/restic", help="where the files will live on the server")
    p.add_argument("--timeout", default="6h", help="TimeoutStartSec for the service (default: 6h)")
    p.add_argument(
        "--on-failure", default="", help="unit to start on failure, e.g. notify-failure@%%n.service"
    )
    p.add_argument(
        "--out", type=Path, default=Path("restic-out"), help="output directory (default: ./restic-out)"
    )
    p.add_argument("--force", action="store_true", help="overwrite existing files in --out")
    p.add_argument("--dry-run", action="store_true", help="print the files instead of writing them")
    args = p.parse_args(argv)

    if not args.path:
        args.path = ["/etc", "/home", "/root", "/var/www", "/srv"]
    errors = []
    if not NAME_RE.match(args.name):
        errors.append("--name must be lowercase letters, digits and hyphens")
    try:
        repo_env_vars(args.repo)
    except ValueError as exc:
        errors.append(str(exc))
    if not ONCALENDAR_RE.match(args.schedule):
        errors.append("--schedule contains unexpected characters")
    for pth in args.path:
        if not pth.startswith("/"):
            errors.append(f"--path must be absolute: {pth}")
    if min(args.keep_daily, args.keep_weekly, args.keep_monthly) < 0:
        errors.append("--keep-* values must be >= 0")
    if errors:
        for e in errors:
            print(f"error: {e}", file=sys.stderr)
        return 2

    files = build_files(args)
    if args.dry_run:
        for fname, content in files.items():
            print(f"===== {fname} =====")
            print(content)
        print(install_steps(args))
        return 0

    args.out.mkdir(parents=True, exist_ok=True)
    existing = [f for f in files if (args.out / f).exists()]
    if existing and not args.force:
        print(f"error: {', '.join(existing)} already exist in {args.out} (use --force)", file=sys.stderr)
        return 2
    for fname, content in files.items():
        (args.out / fname).write_text(content, encoding="utf-8")
    print(f"Wrote {len(files)} files to {args.out}/")
    print(install_steps(args))
    return 0


if __name__ == "__main__":
    sys.exit(main())
